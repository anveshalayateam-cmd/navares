function makeSurfaceTarget(input: ExtendedSurfaceInput): MarsTarget {
  const radSeverity: MarsTarget['radiationSeverity'] =
    input.radiationMsVDay >= 0.85
      ? 'critical'
      : input.radiationMsVDay >= 0.6
        ? 'moderate'
        : 'sheltered';
  const radLabel =
    radSeverity === 'critical'
      ? 'Critical Exposure'
      : radSeverity === 'moderate'
        ? 'Moderate'
        : 'Low / Sheltered';
  const elevSign = input.elevationMeters >= 0 ? '+' : '-';
  const elevFormatted = `${elevSign}${Math.abs(Math.round(input.elevationMeters)).toLocaleString('en-US')} m`;
  return {
    id: input.id,
    name: input.name,
    shortName: input.shortName,
    category: input.category,
    region: input.region,
    latitude: input.latitude,
    longitude: input.longitude,
    elevationLabel: `${elevFormatted} (${input.elevationContext})`,
    elevationMeters: input.elevationMeters,
    surfaceRadiation: `${input.radiationMsVDay.toFixed(2)} mSv/day · ${radLabel}`,
    radiationSeverity: radSeverity,
    surfaceTempRange: `${input.tempMinC}°C to ${input.tempMaxC >= 0 ? `+${input.tempMaxC}` : input.tempMaxC}°C`,
    missionStatus: input.missionStatus,
    agency: input.agency,
    epochOrSol: input.epochOrSol,
    scientificSignificance: input.scientificSignificance,
    searchKeywords: input.searchKeywords,
    photoUrl: input.photoUrl,
    photoCaption: input.photoCaption,
    survivalNotes: {
      slopeSteepness: input.slopeSteepness,
      dustRisk: input.dustRisk,
      radiationLevel: `${input.radiationMsVDay.toFixed(2)} mSv/day calibrated surface dose`,
      thermalRange: `${input.tempMinC} °C night to ${input.tempMaxC >= 0 ? `+${input.tempMaxC}` : input.tempMaxC} °C daytime peak`,
      astronautAdvisory: input.astronautAdvisory,
    },
  };
}

function makeOrbiterTarget(input: ExtendedOrbiterInput): MarsTarget {
  const altitudeMeters = Math.round(input.altitudeKm * 1000);
  const r = MARS_CONSTANTS.EQUATORIAL_RADIUS + altitudeMeters;
  const orbitalVelocityKmS = Number((Math.sqrt(MARS_CONSTANTS.MU_MARS / r) / 1000).toFixed(2));
  const periodMinutes = Number(
    ((2 * Math.PI * Math.sqrt((r * r * r) / MARS_CONSTANTS.MU_MARS)) / 60).toFixed(1)
  );
  const radMsVDay = Number((1.21 + (input.altitudeKm / 2500) * 0.14).toFixed(2));
  return {
    id: input.id,
    name: input.name,
    shortName: input.shortName,
    category: 'satellite',
    region: `${input.region} (${input.altitudeKm} km)`,
    latitude: 0,
    longitude: 0,
    elevationLabel: `${input.altitudeKm.toLocaleString('en-US')} km Altitude · ${input.inclinationDeg}° Inclination`,
    elevationMeters: altitudeMeters,
    surfaceRadiation: `${radMsVDay.toFixed(2)} mSv/day · Unshielded Orbit`,
    radiationSeverity: 'critical',
    surfaceTempRange: '-118°C to +82°C (Bus)',
    missionStatus: input.missionStatus,
    agency: input.agency,
    epochOrSol: input.epochOrSol,
    scientificSignificance: input.scientificSignificance,
    searchKeywords: input.searchKeywords,
    photoUrl: input.photoUrl,
    photoCaption: input.photoCaption,
    survivalNotes: {
      slopeSteepness: `N/A · ${input.inclinationDeg}° orbital inclination (${periodMinutes} min period)`,
      dustRisk: input.dustRisk,
      radiationLevel: `${radMsVDay.toFixed(2)} mSv/day (unshielded orbital cosmic radiation)`,
      thermalRange: '-118 °C eclipse to +82 °C sunlit solar arrays',
      astronautAdvisory: input.astronautAdvisory,
    },
    orbit: {
      altitudeMeters,
      inclinationDeg: input.inclinationDeg,
      raanDeg: input.raanDeg,
      initialPhaseDeg: input.initialPhaseDeg,
      periodMinutes,
      orbitalVelocityKmS,
    },
  };
}

